class Board:
    """A tiny raw-REPL client: runs Python snippets on the board and copies files to it."""

    def __init__(self, port):
        try:
            self.s = serial.Serial(port, 115200, timeout=0.2)
        except (serial.SerialException, OSError) as e:
            stop("cannot open %s (%s).\n  Another program is probably using it: close Thonny's connection to the board "
                 "(Run > Configure interpreter > 'Local Python 3'), or any serial monitor, and try again.\n"
                 "  On Linux you may also need:  sudo usermod -aG dialout $USER   (then log out and in)." % (port, e))
        self.port = port

    def read_until(self, marker, timeout):
        buf = b""
        t0 = time.time()
        while time.time() - t0 < timeout:
            d = self.s.read(256)
            if d:
                buf += d
                if buf.endswith(marker) or marker in buf:
                    return buf
        return buf

    def enter_raw(self):
        self.s.dtr = False                                    # do not let the port opening reset the board mid-way
        self.s.rts = False
        for _ in range(3):
            self.s.write(b"\r\x03\x03")                      # Ctrl-C twice: stop whatever the board is running
            time.sleep(0.2)
            self.s.reset_input_buffer()
            self.s.write(b"\r\x01")                          # Ctrl-A: raw REPL
            if b"raw REPL; CTRL-B to exit" in self.read_until(b">", 2):
                return
        stop("the board does not answer on %s. Is MicroPython installed? Try pressing the board's RESET button and run again." % self.port)

    def run(self, code, timeout=15):
        # Raw-REPL reply:  OK <output> \x04 <errors> \x04 >     (everything after "OK" may arrive in the same chunk)
        self.s.write(code.encode() + b"\x04")
        buf = self.read_until(b"OK", 3)
        i = buf.find(b"OK")
        if i < 0:
            stop("the board did not accept a command.")
        rest = buf[i + 2:]
        t0 = time.time()
        while rest.count(b"\x04") < 2 and time.time() - t0 < timeout:
            rest += self.s.read(256)
        parts = rest.split(b"\x04")
        if len(parts) < 3:
            stop("no complete answer from the board (got %r)." % rest[:80])
        result, err = parts[0], parts[1]
        if err.strip():
            raise RuntimeError(err.decode("utf-8", "replace").strip())
        return result.decode("utf-8", "replace")

    def put(self, data, remote):
        """Write the bytes `data` to the file `remote` on the board and check the size."""
        folder = remote.rsplit("/", 1)[0] if "/" in remote else ""
        if folder:
            self.run("import os\ntry:\n os.mkdir(%r)\nexcept OSError:\n pass" % folder)
        self.run("import binascii\nf = open(%r, 'wb')" % remote)
        for i in range(0, len(data), CHUNK):
            self.run("f.write(binascii.a2b_base64(%r))" % base64.b64encode(data[i:i + CHUNK]).decode())
        self.run("f.close()")
        size = int(self.run("import os\nprint(os.stat(%r)[6])" % remote).strip())
        if size != len(data):
            stop("%s arrived with %d bytes instead of %d." % (remote, size, len(data)))

    def remove(self, name):
        self.run("import os\ntry:\n os.remove(%r)\nexcept OSError:\n pass" % name)

    def listdir(self):
        return eval(self.run("import os\nprint(os.listdir())"))

    def read_text(self, name):
        """A text file on the board, or None. (Held in memory only: never printed.)"""
        try:
            return eval(self.run("try:\n print(repr(open(%r).read()))\nexcept OSError:\n print(repr(None))" % name).strip())
        except Exception:
            return None

    def restart(self):
        self.s.write(b"\x02")                                # Ctrl-B: leave the raw REPL
        time.sleep(0.2)
        self.s.rts = True                                    # RTS is wired to the reset pin on these boards
        time.sleep(0.1)
        self.s.rts = False
        self.s.close()


def pick_port(args, what):
    if "--port" in args:
        return args[args.index("--port") + 1]
    ports = find_ports()
    if not ports:
        stop("no board found. Plug the CYD into the computer with a USB cable that carries data (many cables are charge-only).")
    if len(ports) == 1:
        say("Board found on %s." % ports[0].device)
        return ports[0].device
    say("Several boards are connected. Which one should %s?" % what)
    for i, p in enumerate(ports, 1):
        say("  %d   %s   %s   (USB socket %s)" % (i, p.device, p.description, p.location or "?"))
    say("(Tip: unplug the others first if you are not sure which is which.)")
    choice = input("Type the number: ").strip()
    if not choice.isdigit() or not 1 <= int(choice) <= len(ports):
        stop("no valid choice.")
    return ports[int(choice) - 1].device


def wifi_dialog(b, present, status_only=False, remove=False, ask_first=False):
    """Put the Wi-Fi name and password on the board in the sealed file wifi.dat. Nothing is kept on this computer or printed."""
    id_text = b.read_text("ID.dat") if "ID.dat" in present else None
    id_lines = id_text.split("\n") if id_text else []
    id_has = len(id_lines) > 5 and bool(id_lines[4].strip())
    has_wifi = "wifi.dat" in present
    sealed = False
    if has_wifi:
        head = b.read_text("wifi.dat")
        sealed = bool(head) and head.startswith("wattle1:")
    say("wifi.dat on the board: " + (("yes, sealed" if sealed else "yes, plain text (set it up again to seal it)") if has_wifi else "no"))
    say("Wi-Fi settings in ID.dat (the old place): " + ("yes" if id_has else "no"))
    if status_only:
        return
    if remove:
        b.remove("wifi.dat")
        say("wifi.dat removed.")
        return
    if ask_first:
        say()
        if input("Set up the Wi-Fi name and password on this board now? (Only needed if your programs will use Wi-Fi.) [y/N] ").strip().lower() not in ("y", "yes"):
            say("OK. You can do it later: run this installer again with  --wifi")
            return
    say()
    name = input("Network name (SSID): ").strip()
    if not name:
        say("No network name given; the Wi-Fi settings were not changed.")
        return
    password = getpass.getpass("Password (it is not shown; in Thonny it may be shown, but only on this screen): ")
    if not password:
        say("(No password: the network will be treated as an open network.)")
    text = name + "\n" + password + "\n"
    if "wifi_cipher.py" not in present:
        b.put(load("wifi_cipher.py"), "wifi_cipher.py")
    # The board seals the text itself (its chip id is the key); only the sealed line is stored.
    b.run("import wifi_cipher\nf = open('wifi.dat', 'w')\nf.write(wifi_cipher.seal(%r) + '\\n')\nf.close()" % text)
    check = b.run("import wifi_cipher\nprint(wifi_cipher.unseal(open('wifi.dat').read()) is not None)").strip()
    if check != "True":
        stop("the board could not read back what it sealed. Run this installer again with  --wifi")
    size = int(b.run("import os\nprint(os.stat('wifi.dat')[6])").strip())
    say("wifi.dat written on the board, sealed (%d bytes): it only works on this board. Nothing was saved on this computer." % size)
    if id_has:
        say()
        say("ID.dat on the board still holds Wi-Fi settings in lines 5 and 6.")
        if input("Remove them from ID.dat (wifi.dat now holds them)? [Y/n] ").strip().lower() in ("", "y", "yes"):
            id_lines[4] = ""
            id_lines[5] = ""
            b.run("f = open('ID.dat', 'w')\nf.write(%r)\nf.close()" % "\n".join(id_lines))
            say("Lines 5 and 6 of ID.dat are now empty (the other lines are unchanged).")


def selftest():
    """Check that the files inside this installer decompress, and (when the folder is next to it) match the folder's files."""
    if not EMBEDDED:
        say("Nothing is built into this copy: it reads the files from the folder next to it.")
        return 0
    bad = 0
    for src in sorted(EMBEDDED):
        try:
            data = zlib.decompress(base64.b64decode(EMBEDDED[src]))
        except Exception as e:
            say("  BROKEN   %s (%s)" % (src, e))
            bad += 1
            continue
        path = os.path.join(HERE, src)
        if os.path.exists(path) and open(path, "rb").read() != data:
            say("  DIFFERS  %s (the folder's copy is different: run make_installer.py)" % src)
            bad += 1
        else:
            say("  ok       %-32s %6d bytes" % (src, len(data)))
    say("All %d files inside this installer are intact." % len(EMBEDDED) if not bad else "%d problem(s) found." % bad)
    return 1 if bad else 0


def main(args=None):
    args = sys.argv[1:] if args is None else args
    yes = "--yes" in args
    demo = "--no-demo" not in args

    say("Wattle installer (version 0.9, for the CYD board)")
    say()
    if "--selftest" in args:
        raise SystemExit(selftest())
    if "--list" in args:
        for p in find_ports():
            say("  %s   %s   (USB socket %s)" % (p.device, p.description, p.location or "?"))
        raise SystemExit

    files = [(f, f) for f in PROGRAM_FILES] + [(FONT, FONT)] + [(f, f) for f in OPTIONAL_FILES if load(f) is not None]
    if demo:
        files += DEMO
    if load(FONT) is None:                                          # only used by the red error screens: carry on without it
        say("Note: %s is not available; error messages will use the small built-in font." % FONT)
        files = [f for f in files if f[0] != FONT]
    missing = [src for src, _ in files if load(src) is None]
    if missing:
        stop("these files are missing from this installer: " + ", ".join(missing))
    sizes = {dst: len(load(src)) for src, dst in files}

    if "--dry-run" in args:
        say("These files would be copied to the board:")
        for src, dst in files:
            say("  %-32s %6d bytes" % (dst, sizes[dst]))
        raise SystemExit

    port = pick_port(args, "get the change" if "--wifi" in args else "get Wattle")
    b = Board(port)
    b.enter_raw()
    try:
        present = b.listdir()
    except Exception as e:
        stop("could not read the board's files: %s" % e)
    say("MicroPython answered. Files on the board now: " + (", ".join(sorted(present)) or "(none)"))

    if "--wifi" in args:
        wifi_dialog(b, present, status_only="--status" in args, remove="--remove" in args)
        b.restart()
        return

    old = [n for n in OLD_SOURCES if n in present]
    replaced = [dst for _, dst in files if "/" not in dst and dst in present]
    if old:
        say("These old files will be REMOVED (they would be used instead of the precompiled ones): " + ", ".join(old))
    if replaced:
        say("These will be REPLACED: " + ", ".join(replaced))
    if not yes:
        if input("Install Wattle on %s now? [Y/n] " % port).strip().lower() not in ("", "y", "yes"):
            b.s.close()
            stop("cancelled; nothing was changed.")

    total = sum(sizes.values())
    say()
    for n in old:
        b.remove(n)
    say("Copying %d files (%d KB). This takes about a minute ..." % (len(files), total // 1024))
    for src, dst in files:
        say("  %-32s %6d bytes" % (dst, sizes[dst]))
        b.put(load(src), dst)
    if not yes:
        present = b.listdir()
        wifi_dialog(b, present, ask_first=True)
    b.restart()
    say()
    say("Finished. The board is restarting.")
    if demo:
        say("The screen should show \"Wattle is running!\", a counter \"Taps: 0\" and a button \"Tap me\" within a few seconds. Tap the button: the counter goes up.")
    else:
        say("Wattle is installed. Add a design and a script (see the Quick Guide).")


if __name__ == "__main__":
    main()
