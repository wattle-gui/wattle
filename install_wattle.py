def load(src):
    """The bytes of a file: from inside this installer if it is there, else from the folder next to it, else None."""
    if src in EMBEDDED:
        return zlib.decompress(base64.b64decode(EMBEDDED[src]))
    path = os.path.join(HERE, src)
    if os.path.exists(path):
        with open(path, "rb") as f:
            return f.read()
    return None


