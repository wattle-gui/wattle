# install_wattle.py -- ONE-FILE installer for Wattle on a CYD board (ESP32-2432S028 and compatibles).
#
#   In Thonny:  open this file and press the green Run button.
#   Anywhere:   python3 install_wattle.py            (Windows: python install_wattle.py)
#
# This single file carries everything the board needs (the Wattle program files and a small demo) INSIDE it. There is nothing else
# to download, unzip or find. It looks for the board on the USB cable, copies the files onto it, restarts it, and at the end offers to
# put your Wi-Fi name and password on the board (only needed if your programs will use Wi-Fi).
# Needs only Python and the pyserial module on the computer (Thonny already includes both).
#
#   --port /dev/ttyUSB1     use this port (Windows: --port COM5); skips the question when several boards are connected
#   --no-demo               do not copy the demo
#   --yes                   do not ask any question (no Wi-Fi step either)
#   --list                  only list the boards found, and exit
#   --dry-run               only list the files that would be copied, and exit
#   --wifi                  only the Wi-Fi settings (with --status: say whether the board has them; with --remove: delete them)
#   --selftest              check that the files inside this installer are intact, and exit
#
# The board must already run MicroPython (version 1.24 was used for Wattle 0.9). Files with the same names are replaced; other
# files on the board are left alone. Your own files, ID.dat and wifi settings are never touched by the install.
# (The files inside this installer are put there by make_installer.py, a developer tool. Do not edit that part by hand.)
