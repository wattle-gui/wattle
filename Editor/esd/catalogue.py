def spec_for(widget_kind: str) -> dict[str, Any]:
    return WIDGET_TYPES.get(str(widget_kind or ""), {})


def is_interactive_kind(widget_kind: str) -> bool:
    """Buttons and other touch targets. Decorative types return False."""
    spec = spec_for(widget_kind)
    if "interactive" in spec:
        return bool(spec["interactive"])
    return bool(spec.get("events"))


def make_widget_defaults(widget_kind: str) -> dict[str, Any]:
    spec = spec_for(widget_kind)
    if not spec:
        raise KeyError(f"Unknown widget type: {widget_kind}")
    return deepcopy(spec["defaults"])


def palette_widgets() -> list[tuple[str, str]]:
    """Palette order is alphabetical by the name shown to the user."""
    items = [(k, spec["label"]) for k, spec in WIDGET_TYPES.items()]
    items.sort(key=lambda pair: str(pair[1]).casefold())
    return items


def keyboard_rows(layout: str, *, linefeed: bool) -> list[list[str]]:
    """Key labels for the Keyboard widget. ENT=Enter, BS=Backspace, ESC=cancel, LF=linefeed, SPACE=space.

    Numeric is a 4-column pad. ENT is drawn across the last two rows of the right column.
    The linefeed key is only on the full layout.
    """
    if str(layout or "").lower() == "numeric":
        return [
            ["1", "2", "3", "BS"],
            ["4", "5", "6", "ESC"],
            ["7", "8", "9"],
            ["-", "0", ".", "ENT"],
        ]
    last = ["SPACE", "LF", "ENT"] if linefeed else ["SPACE", "ENT"]
    return [
        list("1234567890"),
        list("QWERTYUIOP"),
        list("ASDFGHJKL"),
        ["Z", "X", "C", "V", "B", "N", "M", "BS"],
        last,
    ]


def resolve_color(value: str) -> str:
    raw = str(value or "").strip()
    if raw.lower() in NAMED_TO_HEX:
        return NAMED_TO_HEX[raw.lower()]
    return raw


def canonical_color(value: str, *, allow_transparent: bool = False) -> str | None:
    """Schema colour, or None when the text is not allowed.

    Named colours or #rrggbb. Transparent is only a switch, checkbox, or stepper background.
    """
    raw = str(value or "").strip()
    low = raw.lower()
    if allow_transparent and low == "transparent":
        return "transparent"
    if low in SCHEMA_COLORS:
        return low
    if len(raw) == 7 and raw[0] == "#" and all(c in "0123456789abcdefABCDEF" for c in raw[1:]):
        return raw.lower()
    return None
